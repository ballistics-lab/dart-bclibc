#!/usr/bin/env python3
"""Embeds the bare wasm module into lib/ffi/bclibc_wasm.g.dart.

The module is ~80 KB, so it ships inside the package as a base64 constant
instead of a Flutter asset: one code path for Dart web, Flutter web and tests,
nothing to bundle or serve.

Usage: scripts/embed_wasm.py path/to/bclibc_wasm.wasm [out.dart]
"""

import base64
import sys
from pathlib import Path

OUT_DEFAULT = Path(__file__).resolve().parent.parent / "lib/ffi/bclibc_wasm.g.dart"


def main() -> None:
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    wasm = Path(sys.argv[1]).read_bytes()
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else OUT_DEFAULT
    b64 = base64.b64encode(wasm).decode()
    chunks = [b64[i : i + 100] for i in range(0, len(b64), 100)]
    body = "\n".join(f"    '{c}'" for c in chunks)
    out.write_text(
        "// GENERATED by scripts/embed_wasm.py (make build-wasm) -- do not edit.\n"
        "// The bare wasm module built from the pinned bclibc submodule.\n"
        "\n"
        f"/// Size of the embedded module in bytes.\n"
        f"const int bclibcWasmSize = {len(wasm)};\n"
        "\n"
        "/// The embedded wasm module, base64-encoded.\n"
        f"const String bclibcWasmBase64 =\n{body};\n"
    )
    print(f"wrote {out} ({len(wasm)} bytes of wasm)")


if __name__ == "__main__":
    main()

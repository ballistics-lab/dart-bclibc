// Build hook: compiles libbclibc_ffi from the bundled bclibc sources
// (dart/bclibc/) into a code asset, `package:bclibc/ffi/bclibc_bindings.g.dart`,
// which the `@Native` bindings in that file resolve at runtime. Same code path
// for `dart run`, `dart test`, `flutter run/build/test` -- nothing is
// downloaded, everything comes from the package archive.
import 'dart:io';

import 'package:code_assets/code_assets.dart';
import 'package:hooks/hooks.dart';
import 'package:native_toolchain_c/native_toolchain_c.dart';

const _sources = [
  'src/base_types.cpp',
  'src/cash_karp.cpp',
  'src/dormand_prince.cpp',
  'src/engine.cpp',
  'src/euler.cpp',
  'src/interp.cpp',
  'src/rk4.cpp',
  'src/traj_data.cpp',
  'src/traj_filter.cpp',
  'src/tsitouras.cpp',
  'src/velocity_verlet.cpp',
  'src/ffi/bclibc_ffi.cpp',
];

void main(List<String> args) async {
  await build(args, (input, output) async {
    if (!input.config.buildCodeAssets) return;

    final root = input.packageRoot.resolve('bclibc/');
    final os = input.config.code.targetOS;

    // version.h is generated by CMake (version.h.in + `git describe`) in the
    // upstream build. A pub archive has no git history, so mirror CMake's
    // fallback ("<MAJOR>.<MINOR>.<PATCH>-dev" with the 0.1.0 default).
    final version = await _describe(root);
    final generated = input.outputDirectory.resolve('generated/');
    final versionHeader = File.fromUri(generated.resolve('bclibc/version.h'));
    await versionHeader.create(recursive: true);
    await versionHeader.writeAsString(_versionHeader(version));

    final isWindows = os == OS.windows;
    await CBuilder.library(
      name: 'bclibc_ffi',
      assetName: 'ffi/bclibc_bindings.g.dart',
      language: Language.cpp,
      std: 'c++17',
      sources: [for (final s in _sources) root.resolve(s).toFilePath()],
      includes: [
        root.resolve('include/').toFilePath(),
        root.resolve('src/').toFilePath(),
        generated.toFilePath(),
      ],
      defines: {
        if (isWindows) ...{'BCLIBC_FFI_EXPORT': null, 'NOMINMAX': null},
      },
      // Strict IEEE arithmetic, matching the CMake build (see upstream
      // CMakeLists.txt: -ffast-math is deliberately not used).
      flags: [
        if (!isWindows) ...[
          '-ffp-contract=off',
          '-ffunction-sections',
          '-fdata-sections',
        ],
        if (os == OS.linux || os == OS.android) ...[
          '-Wl,--gc-sections',
          '-Wl,--version-script=${root.resolve('src/ffi/bclibc_ffi.version').toFilePath()}',
        ],
      ],
    ).run(input: input, output: output);
  });
}

Future<String> _describe(Uri root) async {
  try {
    final r = await Process.run('git', [
      'describe',
      '--tags',
      '--always',
    ], workingDirectory: root.toFilePath());
    final tag = (r.stdout as String).trim();
    if (r.exitCode == 0 && tag.isNotEmpty) {
      return RegExp(r'^v?\d+\.\d+\.\d+').hasMatch(tag)
          ? tag.replaceFirst(RegExp(r'^v'), '')
          : '0.1.0-git-$tag';
    }
  } on ProcessException {
    // no git -- fall through
  }
  return '0.1.0-dev';
}

String _versionHeader(String version) {
  final m = RegExp(r'^(\d+)\.(\d+)\.(\d+)').firstMatch(version);
  final major = m?.group(1) ?? '0';
  final minor = m?.group(2) ?? '1';
  final patch = m?.group(3) ?? '0';
  return '''
#ifndef BCLIBC_VERSION_H
#define BCLIBC_VERSION_H

#define BCLIBC_VERSION_MAJOR $major
#define BCLIBC_VERSION_MINOR $minor
#define BCLIBC_VERSION_PATCH $patch
#define BCLIBC_VERSION "$version"

#endif // BCLIBC_VERSION_H
''';
}
